export interface ImageAsset {
  src: string
  srcSet: string
  width: number
  height: number
}

const asset = (
  small: string,
  large: string,
  sw: number,
  lw: number,
  ratio: number,
  full?: string,
): ImageAsset => ({
  src: small,
  srcSet: `${small} ${sw}w, ${large} ${lw}w${full ? `, ${full} 1600w` : ''}`,
  width: full ? 1600 : lw,
  height: Math.round((full ? 1600 : lw) * ratio),
})

