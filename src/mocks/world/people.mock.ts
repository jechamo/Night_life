export function createMockPeople(): MockPerson[] {
  return ROWS.map(
    (
      [
        name,
        age,
        gender,
        interestedIn,
        light,
        verified,
        placeNow,
        placeTonight,
        likesMe,
        anthem,
        bio,
      ],
      i,
    ) => {
      const id = `p-${i + 1}`
      return {
        id,
        name,
        age,
        gender,
        bio,
        photos: [testAvatarFor(gender, age, i)],
        photoVerified: verified,
        trafficLight: light,
        anthem: anthem === null ? null : (ANTHEMS[anthem] ?? null),
        interestedIn,
        ageMin: Math.max(18, age - 9),
        ageMax: Math.min(60, age + 12),
        discreet: false,
        placeNow,
        placeTonight,
        likesMe,
      }
    },
  )
}

